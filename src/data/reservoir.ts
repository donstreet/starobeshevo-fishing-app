export function currentSeason(date = new Date()): Season {
  const m = date.getMonth()
  if (m >= 2 && m <= 4) return 'spring'
  if (m >= 5 && m <= 7) return 'summer'
  if (m >= 8 && m <= 10) return 'autumn'
  return 'winter'
}

/** Подбор мест под выбранную рыбу, сезон и способ ловли. */
export function rankSpots(fishId: FishId, season: Season, method: Method | 'any') {
  return SPOTS.filter((s) => s.fish.includes(fishId))
    .filter((s) => method === 'any' || s.methods.includes(method))
    .map((s) => {
      const rank = s.fish.indexOf(fishId)
      let score = 10 - rank * 2
      if (s.bestSeasons.includes(season)) score += 4
      if (season === 'spring' && s.restricted) score -= 3
      return { spot: s, score }
    })
    .sort((a, b) => b.score - a.score)
}
